-- 1. VERIFICAR CANTIDAD DE REGISTROS

SELECT 'ROLES' AS TABLA, COUNT(*) AS TOTAL
FROM ROLES
UNION ALL
SELECT 'USUARIOS', COUNT(*) FROM USUARIOS
UNION ALL
SELECT 'CATEGORIAS', COUNT(*) FROM CATEGORIAS
UNION ALL
SELECT 'PUBLICACIONES', COUNT(*) FROM PUBLICACIONES
UNION ALL
SELECT 'COMENTARIOS', COUNT(*) FROM COMENTARIOS;


-- 2. VERIFICAR USUARIOS Y ROLES

SELECT
    U.ID_USUARIO,
    U.NOMBRE,
    U.EMAIL,
    R.NOMBRE AS ROL,
    U.ESTADO
FROM USUARIOS U
INNER JOIN ROLES R
    ON U.ID_ROL = R.ID_ROL
ORDER BY U.ID_USUARIO;


-- 3. VERIFICAR PUBLICACIONES

SELECT
    P.ID_PUBLICACION,
    P.TITULO,
    U.NOMBRE AS AUTOR,
    C.NOMBRE AS CATEGORIA,
    P.ESTADO
FROM PUBLICACIONES P
INNER JOIN USUARIOS U
    ON P.ID_USUARIO = U.ID_USUARIO
INNER JOIN CATEGORIAS C
    ON P.ID_CATEGORIA = C.ID_CATEGORIA
ORDER BY P.ID_PUBLICACION;


-- 4. VERIFICAR COMENTARIOS

SELECT
    C.ID_COMENTARIO,
    P.TITULO AS PUBLICACION,
    U.NOMBRE AS AUTOR,
    C.CONTENIDO,
    C.ESTADO
FROM COMENTARIOS C
INNER JOIN PUBLICACIONES P
    ON C.ID_PUBLICACION = P.ID_PUBLICACION
INNER JOIN USUARIOS U
    ON C.ID_USUARIO = U.ID_USUARIO
ORDER BY C.ID_COMENTARIO;


-- 5. VERIFICAR CATEGORIAS

SELECT
    ID_CATEGORIA,
    NOMBRE,
    DESCRIPCION
FROM CATEGORIAS
ORDER BY ID_CATEGORIA;