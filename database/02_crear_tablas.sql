-- =====================================================
-- TABLA 1: ROLES
-- =====================================================

CREATE TABLE ROLES (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_ROLES
        PRIMARY KEY (ID_ROL),

    CONSTRAINT UK_ROLES_NOMBRE
        UNIQUE (NOMBRE)
);


-- =====================================================
-- TABLA 2: USUARIOS
-- =====================================================

CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ID_ROL NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_USUARIOS
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UK_USUARIOS_EMAIL
        UNIQUE (EMAIL),

    CONSTRAINT FK_USUARIOS_ROLES
        FOREIGN KEY (ID_ROL)
        REFERENCES ROLES(ID_ROL),

    CONSTRAINT CK_USUARIOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- =====================================================
-- TABLA 3: CATEGORIAS
-- =====================================================

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(255),

    CONSTRAINT PK_CATEGORIAS
        PRIMARY KEY (ID_CATEGORIA),

    CONSTRAINT UK_CATEGORIAS_NOMBRE
        UNIQUE (NOMBRE)
);


-- =====================================================
-- TABLA 4: PUBLICACIONES
-- =====================================================

CREATE TABLE PUBLICACIONES (
    ID_PUBLICACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR2(200) NOT NULL,
    CONTENIDO CLOB NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_PUBLICACIONES
        PRIMARY KEY (ID_PUBLICACION),

    CONSTRAINT FK_PUBLICACIONES_USUARIOS
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS(ID_USUARIO),

    CONSTRAINT FK_PUBLICACIONES_CATEGORIAS
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIAS(ID_CATEGORIA),

    CONSTRAINT CK_PUBLICACIONES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);


-- =====================================================
-- TABLA 5: COMENTARIOS
-- =====================================================

CREATE TABLE COMENTARIOS (
    ID_COMENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CONTENIDO CLOB NOT NULL,
    ID_PUBLICACION NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_COMENTARIOS
        PRIMARY KEY (ID_COMENTARIO),

    CONSTRAINT FK_COMENTARIOS_PUBLICACIONES
        FOREIGN KEY (ID_PUBLICACION)
        REFERENCES PUBLICACIONES(ID_PUBLICACION),

    CONSTRAINT FK_COMENTARIOS_USUARIOS
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS(ID_USUARIO),

    CONSTRAINT CK_COMENTARIOS_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);